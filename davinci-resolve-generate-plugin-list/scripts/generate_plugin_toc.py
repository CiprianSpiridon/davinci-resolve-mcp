"""Generate a TOC of every usable DaVinci Resolve plugin/effect/template on this
machine — WITH a functional description for each — and persist it so Claude knows
what's available.

Descriptions come from two ACCURATE sources (nothing invented):
  * Fusion template packs (MotionVFX .drfx): the sub-group folder INSIDE the
    archive (e.g. "Titles › Infographics", "Titles › Social Media",
    "Titles › Call to Action", "Effects › Camera Movements") — this is what the
    pack author filed the template under, so it describes what it does.
  * ResolveFX: a curated one-line description per effect where known; otherwise a
    prettified name (never a fabricated behaviour).

Runs the davinci-resolve-mcp scanners DIRECTLY (filesystem-only — no running
Resolve, no MCP-server restart), reflecting the CURRENT code incl. the
.drfx-expansion fix. Outputs <out>.json + <out>.md, and (optional) a bounded
auto-managed summary block in root CLAUDE.md.

Run with the MCP server's venv python:
  <repo>/.venv/bin/python generate_plugin_toc.py --out ./davinci-plugins --claude-md ./CLAUDE.md
"""
